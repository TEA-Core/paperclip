function nonEmpty(value: string | null | undefined): string | null {
  return typeof value === "string" && value.trim().length > 0 ? value.trim() : null;
}

function expandHomePrefix(value: string): string {
  if (value === "~") return os.homedir();
  if (value.startsWith("~/")) return path.resolve(os.homedir(), value.slice(2));
  return value;
}

function resolveHomeAwarePath(value: string): string {
  return path.resolve(expandHomePrefix(value));
}

function sanitizeWorktreeInstanceId(rawValue: string): string {
  const trimmed = rawValue.trim().toLowerCase();
  const normalized = trimmed
    .replace(/[^a-z0-9_-]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^[-_]+|[-_]+$/g, "");
  return normalized || "worktree";
}

function readEnvEntries(envPath: string): Record<string, string> {
  if (!fs.existsSync(envPath)) return {};
  return parseEnvFile(fs.readFileSync(envPath, "utf8"));
}

function emptyWorktreeEnvFileContents(): string {
  return [
    "# Paperclip environment variables",
    "# Generated by Paperclip worktree repair",
    "",
  ].join("\n");
}

function isPathInside(candidatePath: string, rootPath: string): boolean {
  const candidate = path.resolve(candidatePath);
  const root = path.resolve(rootPath);
  return candidate === root || candidate.startsWith(`${root}${path.sep}`);
}

type WorktreeRuntimeContext = {
  configPath: string;
  envPath: string;
  worktreeName: string;
  instanceId: string;
  homeDir: string;
  instanceRoot: string;
  contextPath: string;
  embeddedPostgresDataDir: string;
  backupDir: string;
  logDir: string;
  storageDir: string;
  secretsKeyFilePath: string;
};

// Keys a refused env file must not steer. config.ts loads the paperclip
// file and then the working-directory file after this snapshot, so a live
// value is operator-owned only when it was already set before either load.
const STEERING_ENV_KEYS = [
  "PAPERCLIP_WORKTREE_NAME",
  "PAPERCLIP_WORKTREES_DIR",
  "PAPERCLIP_SECRETS_MASTER_KEY_FILE",
  "PAPERCLIP_SECRETS_MASTER_KEY",
  "PAPERCLIP_AGENT_JWT_SECRET",
  "BETTER_AUTH_SECRET",
  "DATABASE_URL",
] as const;

type SteeringEnvKey = (typeof STEERING_ENV_KEYS)[number];

let operatorEnvBeforeDotenv: Partial<Record<SteeringEnvKey, string | undefined>> | null = null;
let worktreeBootIsolation: PaperclipConfig | null = null;

export function captureOperatorEnvBeforeDotenv(env: NodeJS.ProcessEnv): void {
  if (operatorEnvBeforeDotenv) return;
  operatorEnvBeforeDotenv = {};
  for (const key of STEERING_ENV_KEYS) {
    operatorEnvBeforeDotenv[key] = env[key];
  }
}

function restoreOperatorSnapshot(): void {
  if (!operatorEnvBeforeDotenv) return;
  for (const key of STEERING_ENV_KEYS) {
    const snapped = operatorEnvBeforeDotenv[key];
    if (typeof snapped === "string" && snapped.length > 0) process.env[key] = snapped;
    else delete process.env[key];
  }
}

export function readWorktreeBootIsolation(): PaperclipConfig | null {
  return worktreeBootIsolation;
}

function operatorProvenValue(key: SteeringEnvKey, live: string | undefined): string | null {
  if (!operatorEnvBeforeDotenv) return null;
  const snapped = nonEmpty(operatorEnvBeforeDotenv[key]);
  if (snapped && snapped === nonEmpty(live)) return snapped;
  return null;
}

function valueNotClaimedByFile(
  key: SteeringEnvKey,
  env: NodeJS.ProcessEnv,
  fileEnv: Record<string, string>,
): string | null {
  const proven = operatorProvenValue(key, env[key]);
  if (proven) return proven;
  const live = nonEmpty(env[key]);
  if (!live) return null;
  const fromFile = nonEmpty(fileEnv[key]);
  if (fromFile !== null && fromFile === live) return null;
  return live;
}

function dropRefusedFileSteering(
  fileEnv: Record<string, string>,
  context: WorktreeRuntimeContext,
): void {
  if (
    fileEnv.DATABASE_URL !== undefined
    && process.env.DATABASE_URL === fileEnv.DATABASE_URL
    && !operatorProvenValue("DATABASE_URL", process.env.DATABASE_URL)
  ) {
    delete process.env.DATABASE_URL;
  }
  if (
    fileEnv.PAPERCLIP_SECRETS_MASTER_KEY_FILE !== undefined
    && process.env.PAPERCLIP_SECRETS_MASTER_KEY_FILE === fileEnv.PAPERCLIP_SECRETS_MASTER_KEY_FILE
    && !operatorProvenValue("PAPERCLIP_SECRETS_MASTER_KEY_FILE", process.env.PAPERCLIP_SECRETS_MASTER_KEY_FILE)
  ) {
    process.env.PAPERCLIP_SECRETS_MASTER_KEY_FILE = context.secretsKeyFilePath;
  }
}

function publishWorktreeBootIsolation(context: WorktreeRuntimeContext): PaperclipConfig | null {
  if (!fs.existsSync(context.configPath)) return worktreeBootIsolation;
  try {
    const parsed = JSON.parse(fs.readFileSync(context.configPath, "utf8")) as PaperclipConfig;
    worktreeBootIsolation = buildIsolatedWorktreeConfig(parsed, context);
    return worktreeBootIsolation;
  } catch {
    return worktreeBootIsolation;
  }
}

// The boot context for a refused env file. Identity comes from the physical
// `.paperclip` layout and from operator env proven not to have been loaded
// out of the refused file. A value dotenv already copied from that file is
// ignored, so the file cannot point this boot at a sibling or main instance.
function resolveWorktreeIsolatedFallbackContext(
  context: WorktreeRuntimeContext,
  env: NodeJS.ProcessEnv,
  fileEnv: Record<string, string> = {},
): WorktreeRuntimeContext {
  const worktreeStateDir = path.dirname(context.configPath);
  const isUidScopedWorktreeState =
    /^uid-\d+$/.test(path.basename(worktreeStateDir))
    && path.basename(path.dirname(worktreeStateDir)) === ".paperclip";
  const worktreeRoot = isUidScopedWorktreeState
    ? path.resolve(worktreeStateDir, "..", "..")
    : path.resolve(worktreeStateDir, "..");
  const worktreeName = valueNotClaimedByFile("PAPERCLIP_WORKTREE_NAME", env, fileEnv)
    ?? path.basename(worktreeRoot);
  const instanceId = sanitizeWorktreeInstanceId(worktreeName);
  const homeDir = resolveHomeAwarePath(
    valueNotClaimedByFile("PAPERCLIP_WORKTREES_DIR", env, fileEnv) ?? "~/.paperclip-worktrees",
  );
  const instanceRoot = path.resolve(homeDir, "instances", instanceId);

  return {
    configPath: context.configPath,
    envPath: context.envPath,
    worktreeName,
    instanceId,
    homeDir,
    instanceRoot,
    contextPath: path.resolve(homeDir, "context.json"),
    embeddedPostgresDataDir: path.resolve(instanceRoot, "db"),
    backupDir: path.resolve(instanceRoot, "data", "backups"),
    logDir: path.resolve(instanceRoot, "logs"),
    storageDir: path.resolve(instanceRoot, "data", "storage"),
    secretsKeyFilePath: path.resolve("/etc/paperclip/worktrees", instanceId, "master.key"),
  };
}

function contextFromWorktreeLayout(env: NodeJS.ProcessEnv): WorktreeRuntimeContext | null {
  if (env.PAPERCLIP_IN_WORKTREE !== "true") return null;
  let configPath: string;
  let envPath: string;
  try {
    configPath = resolvePaperclipConfigPath();
    envPath = resolvePaperclipEnvPath(configPath);
  } catch {
    return null;
  }
  const worktreeStateDir = path.dirname(configPath);
  const isCanonicalWorktreeState = path.basename(worktreeStateDir) === ".paperclip";
  const isUidScopedWorktreeState =
    /^uid-\d+$/.test(path.basename(worktreeStateDir))
    && path.basename(path.dirname(worktreeStateDir)) === ".paperclip";
  if (!isCanonicalWorktreeState && !isUidScopedWorktreeState) return null;
  return resolveWorktreeIsolatedFallbackContext({
    configPath,
    envPath,
    worktreeName: "",
    instanceId: "",
    homeDir: "",
    instanceRoot: "",
    contextPath: "",
    embeddedPostgresDataDir: "",
    backupDir: "",
    logDir: "",
    storageDir: "",
    secretsKeyFilePath: "",
  }, env, {});
}

function resolveWorktreeRuntimeContext(
  env: NodeJS.ProcessEnv,
  overrideConfigPath?: string,
): WorktreeRuntimeContext | null {
  if (env.PAPERCLIP_IN_WORKTREE !== "true") return null;

  const configPath = resolvePaperclipConfigPath(overrideConfigPath);
  const envPath = resolvePaperclipEnvPath(configPath);
  const persistedEnv = readEnvEntries(envPath);

  // PAPERCLIP_IN_WORKTREE can leak in from a parent process or a sourced env
  // file while config resolution still points at a non-worktree target (for
  // example the default instance under <home>/instances/default). Only adopt
  // a target as a worktree when its config sits in a `<root>/.paperclip/`
  // layout, or in the uid-scoped cross-uid variant `<root>/.paperclip/uid-<uid>/`
  // (SUP-14087), and its own persisted env already declares it a worktree;
  // otherwise the repair would rewrite main-instance config and env files.
  const worktreeStateDir = path.dirname(configPath);
  const isCanonicalWorktreeState = path.basename(worktreeStateDir) === ".paperclip";
  const isUidScopedWorktreeState =
    /^uid-\d+$/.test(path.basename(worktreeStateDir))
    && path.basename(path.dirname(worktreeStateDir)) === ".paperclip";
  if (!isCanonicalWorktreeState && !isUidScopedWorktreeState) return null;
  if (persistedEnv.PAPERCLIP_IN_WORKTREE !== "true") return null;

  const persistedConfigPath = nonEmpty(persistedEnv.PAPERCLIP_CONFIG);
  const persistedConfigLooksStale =
    persistedConfigPath !== null &&
    path.resolve(expandHomePrefix(persistedConfigPath)) !== path.resolve(configPath) &&
    !fs.existsSync(resolveHomeAwarePath(persistedConfigPath));
  const stablePersistedEnv = persistedConfigLooksStale ? {} : persistedEnv;
  const worktreeRoot = isUidScopedWorktreeState
    ? path.resolve(worktreeStateDir, "..", "..")
    : path.resolve(worktreeStateDir, "..");
  const worktreeName =
    nonEmpty(stablePersistedEnv.PAPERCLIP_WORKTREE_NAME) ??
    nonEmpty(env.PAPERCLIP_WORKTREE_NAME) ??
    path.basename(worktreeRoot);
  const instanceId =
    nonEmpty(stablePersistedEnv.PAPERCLIP_INSTANCE_ID) ??
    nonEmpty(env.PAPERCLIP_INSTANCE_ID) ??
    sanitizeWorktreeInstanceId(worktreeName);
  const homeDir = resolveHomeAwarePath(
    nonEmpty(stablePersistedEnv.PAPERCLIP_HOME) ??
      nonEmpty(env.PAPERCLIP_HOME) ??
      nonEmpty(env.PAPERCLIP_WORKTREES_DIR) ??
      "~/.paperclip-worktrees",
  );
  const instanceRoot = path.resolve(homeDir, "instances", instanceId);

  return {
    configPath,
    envPath,
    worktreeName,
    instanceId,
    homeDir,
    instanceRoot,
    contextPath: path.resolve(homeDir, "context.json"),
    embeddedPostgresDataDir: path.resolve(instanceRoot, "db"),
    backupDir: path.resolve(instanceRoot, "data", "backups"),
    logDir: path.resolve(instanceRoot, "logs"),
    storageDir: path.resolve(instanceRoot, "data", "storage"),
    secretsKeyFilePath: path.resolve("/etc/paperclip/worktrees", instanceId, "master.key"),
  };
}

function atomicWriteFile(filePath: string, contents: string): void {
  let attempt = 0;

  while (true) {
    const temporaryPath = `${filePath}.tmp-${process.pid}-${attempt}`;
    attempt += 1;
    let fileDescriptor: number | null = null;
    try {
      fileDescriptor = fs.openSync(temporaryPath, "wx", 0o600);
      fs.writeFileSync(fileDescriptor, contents, "utf8");
      fs.fsyncSync(fileDescriptor);
      fs.closeSync(fileDescriptor);
      fileDescriptor = null;
      fs.renameSync(temporaryPath, filePath);
      let directoryDescriptor: number | null = null;
      try {
        directoryDescriptor = fs.openSync(path.dirname(filePath), "r");
        fs.fsyncSync(directoryDescriptor);
      } catch (error) {
        const code = error instanceof Error && "code" in error ? error.code : null;
        if (
          process.platform !== "win32" ||
          !["EACCES", "EINVAL", "EISDIR", "ENOTSUP", "EPERM"].includes(String(code))
        ) {
          throw error;
        }
      } finally {
        if (directoryDescriptor !== null) fs.closeSync(directoryDescriptor);
      }
      return;
    } catch (error) {
      if (fileDescriptor !== null) fs.closeSync(fileDescriptor);
      fs.rmSync(temporaryPath, { force: true });
      const code = error instanceof Error && "code" in error ? error.code : null;
      if (code === "EEXIST") continue;
      throw error;
    }
  }
}

function writeConfigFile(configPath: string, config: PaperclipConfig): boolean {
  fs.mkdirSync(path.dirname(configPath), { recursive: true });
  const update = paperclipConfigSchema.parse(config);
  const source = fs.existsSync(configPath)
    ? paperclipConfigSchema.parse(JSON.parse(fs.readFileSync(configPath, "utf8")))
    : null;
  const nextConfig = source
    ? paperclipConfigSchema.parse(mergePaperclipConfig(source, update))
    : update;

  if (source && isDeepStrictEqual(source, nextConfig)) return false;

  atomicWriteFile(configPath, JSON.stringify(nextConfig, null, 2) + "\n");
  return true;
}

function resolveRepoManagedWorktreesRoot(worktreeRoot: string): string | null {
  const normalized = path.resolve(worktreeRoot);
  const marker = `${path.sep}.paperclip${path.sep}worktrees${path.sep}`;
  const index = normalized.indexOf(marker);
  if (index === -1) return null;
  const repoRoot = normalized.slice(0, index);
  return path.resolve(repoRoot, ".paperclip", "worktrees");
}

function collectSiblingWorktreePorts(
  context: WorktreeRuntimeContext,
  registeredConfigPaths: Iterable<string> = [],
): {
  serverPorts: Set<number>;
  databasePorts: Set<number>;
  configPaths: Set<string>;
} {
  const serverPorts = new Set<number>();
  const databasePorts = new Set<number>();
  const siblingConfigPaths = new Set<string>();
  for (const configPath of registeredConfigPaths) {
    const resolvedConfigPath = path.resolve(configPath);
    if (resolvedConfigPath !== path.resolve(context.configPath) && fs.existsSync(resolvedConfigPath)) {
      siblingConfigPaths.add(resolvedConfigPath);
    }
  }
  const instancesDir = path.resolve(context.homeDir, "instances");
  if (fs.existsSync(instancesDir)) {
    for (const entry of fs.readdirSync(instancesDir, { withFileTypes: true })) {
      if (!entry.isDirectory() || entry.name === context.instanceId) continue;

      const siblingConfigPath = path.resolve(instancesDir, entry.name, "config.json");
      if (fs.existsSync(siblingConfigPath)) {
        siblingConfigPaths.add(siblingConfigPath);
      }
    }
  }

  const repoManagedWorktreesRoot = resolveRepoManagedWorktreesRoot(path.dirname(context.configPath));
  if (repoManagedWorktreesRoot && fs.existsSync(repoManagedWorktreesRoot)) {
    for (const entry of fs.readdirSync(repoManagedWorktreesRoot, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;

      const siblingConfigPath = path.resolve(repoManagedWorktreesRoot, entry.name, ".paperclip", "config.json");
      if (path.resolve(siblingConfigPath) === path.resolve(context.configPath)) continue;
      if (fs.existsSync(siblingConfigPath)) {
        siblingConfigPaths.add(siblingConfigPath);
      }
    }
  }

  for (const siblingConfigPath of siblingConfigPaths) {
    try {
      const siblingConfig = JSON.parse(fs.readFileSync(siblingConfigPath, "utf8")) as PaperclipConfig;
      if (Number.isInteger(siblingConfig.server.port) && siblingConfig.server.port > 0) {
        serverPorts.add(siblingConfig.server.port);
      }
      if (
        Number.isInteger(siblingConfig.database.embeddedPostgresPort) &&
        siblingConfig.database.embeddedPostgresPort > 0
      ) {
        databasePorts.add(siblingConfig.database.embeddedPostgresPort);
      }
    } catch {
      // Ignore sibling configs that are missing or malformed.
    }
  }

  return { serverPorts, databasePorts, configPaths: siblingConfigPaths };
}

function findNextUnclaimedPort(preferredPort: number, claimedPorts: Set<number>): number {
  let port = Math.max(1, Math.trunc(preferredPort));
  while (claimedPorts.has(port)) {
    port += 1;
  }
  return port;
}

function buildIsolatedWorktreeConfig(
  config: PaperclipConfig,
  context: WorktreeRuntimeContext,
  portOverrides?: {
    serverPort?: number;
    databasePort?: number;
  },
): PaperclipConfig {
  const serverPort = portOverrides?.serverPort ?? config.server.port;
  const databasePort =
    config.database.mode === "embedded-postgres"
      ? portOverrides?.databasePort ?? config.database.embeddedPostgresPort
      : undefined;
  const nextConfig: PaperclipConfig = {
    ...config,
    database: {
      ...config.database,
      ...(config.database.mode === "embedded-postgres"
        ? {
            embeddedPostgresDataDir: context.embeddedPostgresDataDir,
            embeddedPostgresPort: databasePort ?? config.database.embeddedPostgresPort,
            backup: {
              ...config.database.backup,
              enabled: false,
              dir: context.backupDir,
            },
          }
        : {}),
    },
    server: {
      ...config.server,
      port: serverPort,
    },
    logging: {
      ...config.logging,
      logDir: context.logDir,
    },
    storage: {
      ...config.storage,
      localDisk: {
        ...config.storage.localDisk,
        baseDir: context.storageDir,
      },
    },
    secrets: {
      ...config.secrets,
      localEncrypted: {
        ...config.secrets.localEncrypted,
        keyFilePath: context.secretsKeyFilePath,
      },
    },
  };

  if (config.auth.baseUrlMode === "explicit" && config.auth.publicBaseUrl) {
    nextConfig.auth = {
      ...config.auth,
      publicBaseUrl: rewriteUrlPort(config.auth.publicBaseUrl, serverPort),
    };
  }

  return nextConfig;
}

function needsWorktreeConfigRepair(
  config: PaperclipConfig,
  context: WorktreeRuntimeContext,
): boolean {
  if (config.database.mode === "embedded-postgres") {
    if (config.database.backup.enabled) {
      return true;
    }
    if (!isPathInside(config.database.embeddedPostgresDataDir, context.instanceRoot)) {
      return true;
    }
    if (!isPathInside(config.database.backup.dir, context.instanceRoot)) {
      return true;
    }
  }

  if (!isPathInside(config.logging.logDir, context.instanceRoot)) {
    return true;
  }
  if (!isPathInside(config.storage.localDisk.baseDir, context.instanceRoot)) {
    return true;
  }
  if (config.secrets.localEncrypted.keyFilePath !== context.secretsKeyFilePath) {
    return true;
  }

  return false;
}

export function applyRuntimePortSelectionToConfig(
  config: PaperclipConfig,
  input: {
    serverPort: number;
    databasePort?: number | null;
    allowServerPortWrite?: boolean;
    allowDatabasePortWrite?: boolean;
  },
): { config: PaperclipConfig; changed: boolean } {
  let changed = false;
  let nextConfig = config;

  if (input.allowServerPortWrite !== false && config.server.port !== input.serverPort) {
    nextConfig = {
      ...nextConfig,
      server: {
        ...nextConfig.server,
        port: input.serverPort,
      },
    };
    changed = true;
  }

  if (
    input.allowDatabasePortWrite !== false &&
    nextConfig.database.mode === "embedded-postgres" &&
    typeof input.databasePort === "number" &&
    nextConfig.database.embeddedPostgresPort !== input.databasePort
  ) {
    nextConfig = {
      ...nextConfig,
      database: {
        ...nextConfig.database,
        embeddedPostgresPort: input.databasePort,
      },
    };
    changed = true;
  }

  if (nextConfig.auth.baseUrlMode === "explicit" && nextConfig.auth.publicBaseUrl) {
    const rewritten = rewriteUrlPort(nextConfig.auth.publicBaseUrl, input.serverPort);
    if (rewritten && rewritten !== nextConfig.auth.publicBaseUrl) {
      nextConfig = {
        ...nextConfig,
        auth: {
          ...nextConfig.auth,
          publicBaseUrl: rewritten,
        },
      };
      changed = true;
    }
  }

  return { config: nextConfig, changed };
}

export function maybeRepairLegacyWorktreeConfigAndEnvFiles(): {
  repairedConfig: boolean;
  repairedEnv: boolean;
} {
  // A content refusal or a filesystem error must not boot the shared
  // instance. The env file stays byte-identical, a warning names it, and
  // this boot uses an isolated config even when that config cannot be
  // persisted.
  worktreeBootIsolation = null;
  let refused = false;
  let fileEnv: Record<string, string> = {};
  let context: WorktreeRuntimeContext | null;
  let skipEnvRepair = false;
  try {
    context = resolveWorktreeRuntimeContext(process.env);
  } catch (error) {
    let envPath = "unknown env file";
    try {
      envPath = resolvePaperclipEnvPath(resolvePaperclipConfigPath());
    } catch {
      // Keep the fallback label; the warning still carries the error.
    }
    console.warn(
      `Skipping worktree env repair for ${envPath}: ${error instanceof Error ? error.message : String(error)}`,
    );
    restoreOperatorSnapshot();
    context = contextFromWorktreeLayout(process.env);
    if (!context) {
      return { repairedConfig: false, repairedEnv: false };
    }
    refused = true;
    skipEnvRepair = true;
  }
  if (!context) {
    return { repairedConfig: false, repairedEnv: false };
  }

  // Compute the env repair before anything else is touched.
  let effectiveContext: WorktreeRuntimeContext = context;
  let existingContents: string | null = null;
  let toolActionSigningSecret = "";
  let repairedContents: string | null = null;
  if (skipEnvRepair) {
    toolActionSigningSecret =
      nonEmpty(process.env.PAPERCLIP_TOOL_ACTION_SIGNING_SECRET) ?? randomBytes(32).toString("hex");
  } else {
    try {
      existingContents = fs.existsSync(context.envPath)
        ? fs.readFileSync(context.envPath, "utf8")
        : null;
      fileEnv = parseEnvFile(existingContents ?? "");
      // The worktree file wins. An inherited value is used for this boot only
      // and never persisted, so a parent shell's secret cannot become the
      // worktree's own (SUP-24365).
      const inheritedToolActionSigningSecret = nonEmpty(process.env.PAPERCLIP_TOOL_ACTION_SIGNING_SECRET);
      const fileToolActionSigningSecret = nonEmpty(fileEnv.PAPERCLIP_TOOL_ACTION_SIGNING_SECRET);
      toolActionSigningSecret =
        fileToolActionSigningSecret ??
        inheritedToolActionSigningSecret ??
        randomBytes(32).toString("hex");

      const managedEnvEntries: Record<string, string> = {
        PAPERCLIP_HOME: context.homeDir,
        PAPERCLIP_INSTANCE_ID: context.instanceId,
        PAPERCLIP_CONFIG: context.configPath,
        PAPERCLIP_CONTEXT: context.contextPath,
        PAPERCLIP_IN_WORKTREE: "true",
        PAPERCLIP_DB_BACKUP_ENABLED: "false",
        PAPERCLIP_WORKTREE_NAME: context.worktreeName,
        ...(fileToolActionSigningSecret || toolActionSigningSecret === inheritedToolActionSigningSecret
          ? {}
          : { PAPERCLIP_TOOL_ACTION_SIGNING_SECRET: toolActionSigningSecret }),
      };

      repairedContents = updateEnvFileContents(
        existingContents ?? emptyWorktreeEnvFileContents(),
        managedEnvEntries,
        { valueEncoding: "json" },
      );
    } catch (error) {
      console.warn(
        `Skipping worktree env repair for ${context.envPath}: ${error instanceof Error ? error.message : String(error)}`,
      );
      repairedContents = null;
      refused = true;
      restoreOperatorSnapshot();
      effectiveContext = resolveWorktreeIsolatedFallbackContext(context, process.env, fileEnv);
      if (!toolActionSigningSecret) {
        toolActionSigningSecret =
          nonEmpty(process.env.PAPERCLIP_TOOL_ACTION_SIGNING_SECRET) ?? randomBytes(32).toString("hex");
      }
    }
  }
  let repairedEnv = repairedContents !== null && existingContents !== repairedContents;

  if (refused) {
    dropRefusedFileSteering(fileEnv, effectiveContext);
  }

  process.env.PAPERCLIP_HOME = effectiveContext.homeDir;
  process.env.PAPERCLIP_INSTANCE_ID = effectiveContext.instanceId;
  process.env.PAPERCLIP_CONFIG = effectiveContext.configPath;
  process.env.PAPERCLIP_CONTEXT = effectiveContext.contextPath;
  process.env.PAPERCLIP_WORKTREE_NAME = effectiveContext.worktreeName;

  let repairedConfig = false;
  if (fs.existsSync(effectiveContext.configPath)) {
    try {
      const runtimeConfig = withWorktreePortRegistryLockSync(effectiveContext.homeDir, () => {
        const parsed = JSON.parse(fs.readFileSync(effectiveContext.configPath, "utf8")) as PaperclipConfig;
        let selectedConfig = parsed;
        const registeredConfigPaths = readWorktreePortRegistry(effectiveContext.homeDir);
        const siblingPorts = collectSiblingWorktreePorts(effectiveContext, registeredConfigPaths);
        const serverPortCollision = siblingPorts.serverPorts.has(parsed.server.port);
        const databasePortCollision =
          parsed.database.mode === "embedded-postgres" &&
          siblingPorts.databasePorts.has(parsed.database.embeddedPostgresPort);

        if (needsWorktreeConfigRepair(parsed, effectiveContext) || serverPortCollision || databasePortCollision) {
          const selectedServerPort = findNextUnclaimedPort(
            parsed.server.port === 3100 ? 3101 : parsed.server.port,
            siblingPorts.serverPorts,
          );
          const selectedDatabasePort =
            parsed.database.mode === "embedded-postgres"
              ? findNextUnclaimedPort(
                  parsed.database.embeddedPostgresPort === 54329
                    ? 54330
                    : parsed.database.embeddedPostgresPort,
                  new Set([...siblingPorts.databasePorts, selectedServerPort]),
                )
              : undefined;

          selectedConfig = buildIsolatedWorktreeConfig(parsed, effectiveContext, {
            serverPort: selectedServerPort,
            databasePort: selectedDatabasePort,
          });
          worktreeBootIsolation = selectedConfig;
          writeConfigFile(effectiveContext.configPath, selectedConfig);
          repairedConfig = true;

          if (serverPortCollision || databasePortCollision) {
            console.warn(
              [
                `Worktree port conflict detected for ${effectiveContext.worktreeName}; updated and persisted workspace ports.`,
                ...(serverPortCollision
                  ? [`server: ${parsed.server.port} -> ${selectedServerPort}`]
                  : []),
                ...(databasePortCollision && parsed.database.mode === "embedded-postgres"
                  ? [`database: ${parsed.database.embeddedPostgresPort} -> ${selectedDatabasePort}`]
                  : []),
              ].join(" "),
            );
          }
        }

        writeWorktreePortRegistry(effectiveContext.homeDir, [
          ...registeredConfigPaths,
          ...siblingPorts.configPaths,
          effectiveContext.configPath,
        ]);
        return selectedConfig;
      });

      if (
        !nonEmpty(process.env.PORT)
        && Number.isInteger(runtimeConfig.server.port)
        && runtimeConfig.server.port > 0
      ) {
        process.env.PORT = String(runtimeConfig.server.port);
      }
    } catch (error) {
      const reason = error instanceof Error ? error.message : String(error);
      console.warn(
        `Could not persist isolated worktree config at ${effectiveContext.configPath}: ${reason}`,
      );
      if (!worktreeBootIsolation) {
        publishWorktreeBootIsolation(effectiveContext);
      }
      if (!worktreeBootIsolation) {
        const reason = error instanceof Error ? error.message : String(error);
        throw new Error(
          `Refusing to boot on the on-disk config at ${effectiveContext.configPath}: ${reason}`,
        );
      }
    }
  }

  process.env.PAPERCLIP_DB_BACKUP_ENABLED = "false";
  process.env.PAPERCLIP_TOOL_ACTION_SIGNING_SECRET = toolActionSigningSecret;

  if (repairedEnv && repairedContents !== null) {
    try {
      writeEnvFileAtomicallyIfChanged(effectiveContext.envPath, existingContents, repairedContents);
    } catch (error) {
      console.warn(
        `Skipping worktree env repair for ${effectiveContext.envPath}: ${error instanceof Error ? error.message : String(error)}`,
      );
      repairedEnv = false;
    }
  }

  return { repairedConfig, repairedEnv };
}

function isPortPinnedByRuntimeEnv(rawValue: string | null | undefined, selectedPort: number): boolean {
  const normalized = nonEmpty(rawValue);
  if (!normalized) return false;
  const parsedPort = Number(normalized);
  if (!Number.isInteger(parsedPort) || parsedPort <= 0) return true;
  return parsedPort === selectedPort;
}

export function maybePersistWorktreeRuntimePorts(input: {
  serverPort: number;
  databasePort?: number | null;
}): void {
  const context = resolveWorktreeRuntimeContext(process.env);
  if (!context || !fs.existsSync(context.configPath)) return;

  let fileConfig: PaperclipConfig;
  try {
    fileConfig = JSON.parse(fs.readFileSync(context.configPath, "utf8")) as PaperclipConfig;
  } catch {
    return;
  }

  const { config, changed } = applyRuntimePortSelectionToConfig(fileConfig, {
    serverPort: input.serverPort,
    databasePort: input.databasePort,
    allowServerPortWrite: !isPortPinnedByRuntimeEnv(process.env.PORT, input.serverPort),
    allowDatabasePortWrite: !nonEmpty(process.env.DATABASE_URL),
  });

  if (changed) {
    writeConfigFile(context.configPath, config);
  }
}
